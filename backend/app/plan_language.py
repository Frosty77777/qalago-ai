def distance_text(meters: int, language: str) -> str:
    if meters < 1000:
        return f"{round(meters / 10) * 10} {'m' if language == 'en' else 'м'}"
    km = f"{meters / 1000:.1f}"
    return f"{km if language == 'en' else km.replace('.', ',')} {'km' if language == 'en' else 'км'}"
